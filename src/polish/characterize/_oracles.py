"""Turning recorded calls into tests, and refusing to keep the ones that vary.

The generated test is the narrowest possible claim: *this call, observed
returning this, still returns this*. It is written as a `repr` comparison rather
than an `==` one, which is deliberate and does more work than it looks like it
does — `repr` is sensitive to dict and set ordering, so iteration order becomes
a first-class determinism signal (issue #13, criterion 6) instead of something a
tolerant `==` would silently forgive.

Then **replay before trust** (issue #5). Each generated test is run R times
against unmodified code, and anything that does not pass identically every time
is *discarded and never emitted* — not quarantined. Polish owns these tests, so
a non-deterministic one should not exist. This is stricter than the rule for the
user's own suite, and the asymmetry is the whole point:

    a flaky user test    drops good work
    a flaky oracle       can pass a broken change

The second is a false green on the precise claim the product sells, which is why
this module would rather emit nothing than emit something unreliable. Code left
with no surviving oracle is reported as such and stays at Tier 0 (#15 enforces
the eligibility rule; here it is simply the truth being recorded).
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from polish.probe import ORACLES

from ._result import ABSENT, Discarded, Oracle
from ._session import Session

#: Anything that is not usable in a Python identifier.
UNSAFE = re.compile(r"\W")

PYTEST_INI = """\
[pytest]
# Polish's own, so that the repository's addopts and testpaths do not decide
# whether Polish's generated tests are trustworthy.
"""

HEADER = '''\
"""Characterization tests generated by Polish from real execution.

Each assertion below is one call that was observed happening while the
repository's own suite ran, together with what it was observed returning. They
are not hand-written tests and they are not a specification: they record
behaviour, so that a refactor can be checked against it.

Generated. Do not edit — this file is rewritten on every run.
"""

import {module}
'''


@dataclass(frozen=True)
class Candidate:
    """One recorded call, before replay has decided whether to trust it."""

    module: str
    qualname: str
    filename: str
    test: str
    call: str
    expected: str

    @property
    def symbol(self) -> str:
        return f"{self.module}.{self.qualname}"

    @property
    def nodeid(self) -> str:
        return f"{self.filename}::{self.test}"

    def source(self) -> str:
        return (
            f"\n\ndef {self.test}() -> None:\n"
            f"    assert repr({self.call}) == {self.expected!r}\n"
        )


@dataclass(frozen=True)
class Emitted:
    oracles: tuple[Oracle, ...] = ()
    discarded: tuple[Discarded, ...] = ()
    declined: str = ""


def emit(session: Session, samples: Sequence[dict]) -> Emitted:
    """Write the candidates, replay them R times, keep only what never varied."""
    candidates = _candidates(samples)
    if not candidates:
        return Emitted()

    _write(session.oracle_dir, candidates)

    replays = session.repeat(
        ORACLES, session.policy.oracle_seconds, session.policy.replays
    )
    refused = [replay.error for replay in replays if not replay.ok]
    if refused:
        # No replay, no trust. The candidates are removed rather than left on
        # disk unverified, so that nothing downstream can pick up a file whose
        # determinism was never established.
        _write(session.oracle_dir, [])
        return Emitted(declined=f"the replay could not run — {refused[0]}")

    kept, discarded = _survivors(candidates, [replay.tests for replay in replays])
    _write(session.oracle_dir, kept)
    return Emitted(
        oracles=tuple(
            Oracle(
                symbol=item.symbol,
                nodeid=item.nodeid,
                call=item.call,
                expected=item.expected,
            )
            for item in kept
        ),
        discarded=tuple(discarded),
    )


def _candidates(samples: Sequence[dict]) -> list[Candidate]:
    counts: dict[str, int] = {}
    filenames: dict[str, str] = {}
    found: list[Candidate] = []

    for sample in samples:
        module = str(sample.get("module", ""))
        qualname = str(sample.get("qualname", ""))
        if not module or not qualname:
            continue
        symbol = f"{module}.{qualname}"
        index = counts.get(symbol, 0)
        counts[symbol] = index + 1
        arguments = ", ".join(str(item) for item in sample.get("arguments", ()))
        found.append(
            Candidate(
                module=module,
                qualname=qualname,
                filename=_filename(module, filenames),
                test=f"test_{_slug(qualname)}_{index}",
                call=f"{symbol}({arguments})",
                expected=str(sample.get("expected", "")),
            )
        )
    return found


def _filename(module: str, taken: dict[str, str]) -> str:
    """One file per module, with collisions between slugs resolved rather than lost.

    `a.b` and `a_b` slug to the same name, and two modules writing to one file
    would mean the second silently replacing the first.
    """
    if module in taken:
        return taken[module]
    stem = f"test_polish_{_slug(module)}"
    candidate, suffix = f"{stem}.py", 1
    while candidate in set(taken.values()):
        suffix += 1
        candidate = f"{stem}_{suffix}.py"
    taken[module] = candidate
    return candidate


def _slug(name: str) -> str:
    return UNSAFE.sub("_", name)


def _write(directory: Path, candidates: Sequence[Candidate]) -> None:
    """Replace the oracle directory's contents with exactly `candidates`.

    Rewritten rather than appended to, and the previous files are removed first.
    A discarded oracle that stayed on disk would still be collected by the next
    `oracles` run, which would make discarding it a gesture rather than a rule.
    """
    directory.mkdir(parents=True, exist_ok=True)
    for stale in directory.glob("test_*.py"):
        stale.unlink()
    (directory / "pytest.ini").write_text(PYTEST_INI, encoding="utf-8")

    grouped: dict[str, list[Candidate]] = {}
    for candidate in candidates:
        grouped.setdefault(candidate.filename, []).append(candidate)

    for filename, found in grouped.items():
        body = HEADER.format(module=found[0].module)
        body += "".join(candidate.source() for candidate in found)
        (directory / filename).write_text(body, encoding="utf-8")


def _survivors(
    candidates: Sequence[Candidate], replays: Sequence[dict[str, str]]
) -> tuple[list[Candidate], list[Discarded]]:
    kept: list[Candidate] = []
    discarded: list[Discarded] = []

    for candidate in candidates:
        outcomes = tuple(replay.get(candidate.nodeid, ABSENT) for replay in replays)
        if all(outcome == "passed" for outcome in outcomes):
            kept.append(candidate)
            continue
        discarded.append(
            Discarded(
                symbol=candidate.symbol,
                nodeid=candidate.nodeid,
                reason=_why(outcomes),
            )
        )
    return kept, discarded


def _why(outcomes: Sequence[str]) -> str:
    """Report what was observed, without diagnosing more than was observed.

    An oracle that *varies* between replays is visibly non-deterministic. An
    oracle that fails in every replay is not visibly anything: the recorded
    value may drift every time (a clock), or the recording may simply have
    depended on state the replay does not reproduce. Those are different
    problems and the outcomes cannot tell them apart, so this says what happened
    and stops there. Naming a cause Polish has not established would be the same
    manufactured confidence the oracles themselves refuse.
    """
    if len(set(outcomes)) > 1:
        return f"varied across {len(outcomes)} replays: {' / '.join(outcomes)}"
    return (
        f"did not reproduce on unmodified code "
        f"({outcomes[0]} in all {len(outcomes)} replays)"
    )
